import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const directory = new URL('../assets/devices/iphone-18-pro-max/', import.meta.url);
const info = JSON.parse(await readFile(new URL('asset-info.json', directory), 'utf8'));
assert.deepEqual(Object.keys(info.palettes), ['burgundy', 'glacier-blue', 'silver', 'black'], 'Only the four official finish options should ship');
const binary = await readFile(new URL('iphone-18-pro-max.glb', directory));
assert.equal(binary.readUInt32LE(0), 0x46546c67);
assert.equal(binary.readUInt32LE(4), 2);
assert.equal(binary.readUInt32LE(8), binary.length);
assert.equal(createHash('sha256').update(binary).digest('hex'), info.sha256);
assert.equal(binary.length, info.bytes);
const gltf = JSON.parse(binary.subarray(20, 20 + binary.readUInt32LE(12)).toString());
const names = new Set(gltf.nodes.map(node => node.name));
for (const name of ['Screen', 'DynamicIsland', 'FrontCamera', 'UnibodyFrame', 'RearCeramicPanel', 'CameraPlateau', 'ActionButton', 'VolumeUp', 'VolumeDown', 'SideButton', 'CameraControl', 'USBCOpening', 'TrueToneFlash', 'LiDAR', 'AppleEmblem']) assert(names.has(name), `Missing mesh: ${name}`);
for (let i = 1; i <= 3; i++) assert(names.has(`CameraGlass${i}`));
for (const name of ['CameraShoulder', 'CameraPlateauSeam', 'RearFrameLip', 'FlashCover', 'FlashCenter', 'RearAntennaReturn_1', 'RearMicrophoneBevel']) assert(names.has(name), `Missing reference detail: ${name}`);
const boundsFor = name => gltf.accessors[gltf.meshes[gltf.nodes.find(node => node.name === name).mesh].primitives[0].attributes.POSITION];
const rearPanel = boundsFor('RearCeramicPanel');
assert(rearPanel.max[1]-rearPanel.min[1] < 0.12, 'Lower glass must be a separate inset panel');
const cameraDeck = boundsFor('CameraPlateau');
assert(cameraDeck.max[1]-cameraDeck.min[1] < 0.041, 'Camera plateau must match the shorter reference silhouette');
assert(gltf.materials.find(material => material.name === 'BackGlass').normalTexture, 'Packed grain must survive GLB export');
assert(gltf.materials.find(material => material.name === 'LensCover').extensions.KHR_materials_transmission.transmissionFactor > 0.9, 'Optical cover must transmit the recessed lens');
assert.equal(gltf.meshes.length, info.meshCount);
assert.equal(gltf.nodes.filter(node => node.camera !== undefined).length, 0, 'GLB must not ship Blender studio cameras');
const screen = gltf.nodes.find(node => node.name === 'Screen');
const primitive = gltf.meshes[screen.mesh].primitives[0];
assert(primitive.attributes.TEXCOORD_0 !== undefined, 'Screen requires UVs');
assert(gltf.accessors[primitive.attributes.POSITION].count > 100, 'Screen must have rounded geometry');
const position = gltf.accessors[primitive.attributes.POSITION];
assert(Math.abs((position.max[0]-position.min[0]) / (position.max[1]-position.min[1]) - 1320/2868) < 0.0001, 'Screen aspect must match mapping');
for (const palette of Object.values(info.palettes)) for (const material of Object.keys(palette)) assert(gltf.materials.some(item => item.name === material), `Missing finish material ${material}`);
assert(gltf.images.every(image => image.bufferView !== undefined), 'GLB must be self-contained');
console.log(JSON.stringify({ status: 'passed', meshes: gltf.meshes.length, bytes: binary.length, sha256: info.sha256, checks: ['GLB integrity', 'manifest hash', 'all hardware meshes', 'rounded UV screen aspect', 'finish material slots', 'embedded textures', 'no studio cameras'] }, null, 2));
